/**
 * Utils.randomID (public/utils/utils.js): a new calendar's default name is its edit key, so it
 * must come from crypto.getRandomValues (never Math.random), be unbiased over its 33-character
 * alphabet, and new default names are 10 characters (names made before keep their 8).
 *
 * Run: npm run test:unit
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ALPHABET = '123456789abcdefghjklmnpqrstuvwxyz';
const root = path.join(__dirname, '../..');

function loadUtils(cryptoImpl) {
  const src = fs.readFileSync(path.join(root, 'public/utils/utils.js'), 'utf8');
  const fakeDocument = { body: null, addEventListener: () => {}, querySelector: () => null, createElement: () => ({}) };
  const factory = new Function('window', 'document', 'crypto', 'localStorage', 'MutationObserver', `${src}; return window.Utils;`);
  return factory({}, fakeDocument, cryptoImpl, { getItem: () => null, setItem: () => {} }, class { observe() {} });
}

test('randomID: uses crypto.getRandomValues, never Math.random', () => {
  let calls = 0;
  const Utils = loadUtils({ getRandomValues: (a) => { calls++; return globalThis.crypto.getRandomValues(a); } });
  const orig = Math.random;
  Math.random = () => { throw new Error('Math.random must not be used for calendar names'); };
  try {
    const id = Utils.randomID(10);
    assert.equal(id.length, 10);
    assert.ok([...id].every((c) => ALPHABET.includes(c)), id);
    assert.ok(calls >= 1);
  } finally { Math.random = orig; }
});

test('randomID: bytes that would bias the alphabet (>= 231) are skipped, not wrapped', () => {
  // First call: every byte is in the biased tail; second: bytes 0..19 -> the first 20 letters in order.
  let call = 0;
  const Utils = loadUtils({ getRandomValues: (a) => { a.fill(0).forEach((_, i) => { a[i] = call === 0 ? 231 + (i % 25) : i; }); call++; return a; } });
  assert.equal(Utils.randomID(10), ALPHABET.slice(0, 10));
  assert.equal(call, 2, 'a batch with no usable byte is replaced, never used');
});

test('randomID: roughly uniform over the alphabet', () => {
  const Utils = loadUtils(globalThis.crypto);
  const counts = Object.fromEntries([...ALPHABET].map((c) => [c, 0]));
  for (let i = 0; i < 9900; i++) for (const c of Utils.randomID(10)) counts[c]++;
  for (const [c, n] of Object.entries(counts)) assert.ok(n > 2500 && n < 3500, `${c}: ${n}`);
});

test('new default calendar names are 10 characters; 8-character ones still count as auto-generated', () => {
  for (const file of ['public/app.js', 'public/nativecal/app.js']) {
    const src = fs.readFileSync(path.join(root, file), 'utf8');
    assert.ok(!/randomID\(8\)/.test(src), `${file} still makes 8-character names`);
    assert.ok(/randomID\(10\)/.test(src), `${file} makes 10-character names`);
    const m = /isAutogeneratedId\(\) \{[\s\S]*?return (\/.*\/i)\.test\(id\);/.exec(src);
    assert.ok(m, `${file}: isAutogeneratedId not found`);
    const re = eval(m[1]);
    assert.ok(re.test('a2b3c4d5'), 'old 8-character names');
    assert.ok(re.test('a2b3c4d5e6'), 'new 10-character names');
    assert.ok(!re.test('a2b3c4d5e'), 'other lengths are names people chose');
  }
});
